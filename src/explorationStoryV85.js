export const EXPLORATION_CHOICES=Object.freeze(['go','scout','salvage','stay']);
export const EXPLORATION_OUTCOMES=Object.freeze(['item','supplies','injury','sickness','empty','safe']);
export function explorationScene(id){return EXPLORATION_STORIES[id]||null;}
export function explorationOutcomeStory(id,choice,outcome){
 const site=explorationScene(id);
 if(!site)return '';
 if(outcome==='safe')return '위험을 피하고 옥상으로 돌아가기로 했다. 이 장소는 아직 방문 기록에 남지 않는다.';
 return [site[choice]||'',site[outcome]||''].filter(Boolean).join(' ');
}
export function explorationTrail(id){
 return explorationScene(id)?.trail||'';
}
