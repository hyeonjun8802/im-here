#!/usr/bin/env python3
"""Offline 3D raster screenshots from actual GLB geometry (OpenCV software renderer).
Not a Three.js browser capture; images are generated by projecting actual GLB triangles.
"""
from pathlib import Path
import trimesh, numpy as np, cv2
from PIL import Image, ImageDraw, ImageFont
P=Path(__file__).resolve().parents[1];QA=P/'docs/qa';QA.mkdir(parents=True,exist_ok=True)
G=trimesh.load(P/'public/assets/models/afterday/afterday_bearded_survivor_v190.glb',force='scene')
def gather_scene_items(scene):
 items=[]
 for node in scene.graph.nodes_geometry:
  tf,gname=scene.graph[node]; mesh=scene.geometry[gname]
  verts=trimesh.transform_points(mesh.vertices,tf).astype(np.float32)
  face=mesh.faces
  # face normals recompute after transform, correctly handles mirror
  tri=verts[face];nn=np.cross(tri[:,1]-tri[:,0],tri[:,2]-tri[:,0]);nn/=np.linalg.norm(nn,axis=1,keepdims=True)+1e-12
  material=getattr(mesh.visual,'material',None)
  rgba=getattr(material,'baseColorFactor',[170,160,140,255]);rgb=np.array(rgba[:3],dtype=np.float32)
  items.append((verts,face,nn,rgb))
 return items
items=gather_scene_items(G)

W,H=650,810
KEY=np.array([.5,.83,1.2]);KEY/=np.linalg.norm(KEY)
FILL=np.array([-.82,.26,.5]);FILL/=np.linalg.norm(FILL)
RIM=np.array([-.2,.65,-.9]);RIM/=np.linalg.norm(RIM)

def render(cam,filename):
 cam=np.array(cam,float);at=np.array([0,1.46,0]);forward=(at-cam);forward/=np.linalg.norm(forward)
 right=np.cross(forward,[0,1,0]);right/=np.linalg.norm(right);up=np.cross(right,forward)
 mat=np.array([right,up,forward])
 im=np.zeros((H,W,3),dtype=np.uint8)
 for y in range(H):
  v=y/H;im[y,:,:]=(np.array([23,34,44])*(1-v)+np.array([15,23,28])*v).astype(np.uint8)[::-1]
 # floor shadow ellipse near boots
 cv2.ellipse(im,(W//2,int(H*.85)),(82,10),0,0,360,(18,25,30),-1,cv2.LINE_AA)
 batches=[]
 for verts,face,norms,base in items:
  rel=verts-cam;proj=rel@mat.T;depth=proj[:,2]
  f=H*1.60
  xy=np.column_stack((W/2+proj[:,0]*f/np.maximum(depth,.01),H*.54-proj[:,1]*f/np.maximum(depth,.01))).astype(np.int32)
  tris=xy[face];face_depth=depth[face].mean(axis=1)
  cent=verts[face].mean(axis=1)
  facing=(norms*(cam-cent)).sum(axis=1)
  box=((tris[:,:,0].max(1)>=0)&(tris[:,:,0].min(1)<W)&(tris[:,:,1].max(1)>=0)&(tris[:,:,1].min(1)<H))
  vis=(face_depth>0.01)&box&(facing>-.01)
  if not vis.any():continue
  norms2=norms[vis];ind=tris[vis];dd=face_depth[vis]
  diff=(norms2@KEY).clip(0,None)*.70+(norms2@FILL).clip(0,None)*.25+(norms2@RIM).clip(0,None)*.23+.33
  col=np.clip(base[None,:]*diff[:,None],0,255).astype(np.uint8)
  batches.append((ind,dd,col))
 I=np.concatenate([x[0] for x in batches]);D=np.concatenate([x[1] for x in batches]);C=np.concatenate([x[2] for x in batches]);idx=np.argsort(-D)
 for j in idx:
  t=I[j];
  # ignore sub-pixel tiny faces; nearby triangle surfaces still fill the area
  if (t[:,0].max()-t[:,0].min()<1 and t[:,1].max()-t[:,1].min()<1):continue
  cv2.fillConvexPoly(im,t,C[j,::-1].tolist(),lineType=cv2.LINE_AA)
 img=cv2.cvtColor(im,cv2.COLOR_BGR2RGB)
 Image.fromarray(img).save(QA/filename)
 print('rendered',filename,len(idx),'visible triangles')

if __name__ == "__main__":
 views=[('front',(0,1.6,7.1)),('three_quarter',(4.4,2.0,6)),('side',(7.1,1.6,.1)),('back',(0,1.6,-7.1))]
 for name,cam in views:render(cam,'character_'+name+'.png')
 contacts=Image.new('RGB',(4*480,630),(18,23,29))
 fontpath='/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
 font=ImageFont.truetype(fontpath,22)
 for i,(name,_) in enumerate(views):
  img=Image.open(QA/('character_'+name+'.png')).convert('RGB');img.thumbnail((468,574))
  x=i*480+(480-img.width)//2;contacts.paste(img,(x,40))
  ImageDraw.Draw(contacts).text((i*480+16,8),name.replace('_',' ').upper(),font=font,fill=(227,215,195))
 contacts.save(QA/'CHARACTER_3D_MULTIVIEW_QA.jpg',quality=92)
